@Serializable
data class BackupSelection(
    val localBookCache: Boolean = true,
    val bookshelf: Boolean = true,
    val readingRecord: Boolean = true,
    val settings: Boolean = true,
    val bookshelfId: Identifier.Bookshelf? = null,
    val sourceNamespace: String? = null
) {
    fun includes(group: BackupGroup): Boolean = when (group) {
        BackupGroup.METADATA -> true
        BackupGroup.CACHE -> localBookCache
        BackupGroup.BOOKSHELF -> bookshelf
        BackupGroup.READING -> readingRecord
        BackupGroup.SETTINGS -> settings
        BackupGroup.USER_DATA -> readingRecord || settings
    }
}

@Serializable
private data class BackupManifest(val containerVersion: Int, val selection: BackupSelection)
data class BackupTableInfo(
    val name: String,
    val group: BackupGroup,
    val scopeColumn: String,
    val scopeType: String,
    val autoGeneratedKey: String? = null
)

/** SQLite 负责行数据存储, Room 负责建库和增量迁移 */
class SQLiteBackup(private val context: Context, private val database: LightNovelReaderDatabase) {
    suspend fun export(output: OutputStream, selection: BackupSelection) =
        withContext(Dispatchers.IO) {
            val file = File.createTempFile("export-", ".sqlite", context.cacheDir)
            try {
                LightNovelReaderDatabase.openFile(context, file).use { destination ->
                    val target = destination.openHelper.writableDatabase
                    database.withTransaction {
                        // 目标库的事务须与写入操作在同一个 Room 事务线程上执行
                        target.beginTransaction()
                        try {
                            val source = database.openHelper.writableDatabase
                            val shelf = if (selection.bookshelfId != null) database.bookshelfDao()
                                .getBookshelf(selection.bookshelfId)
                                ?: error("Bookshelf does not exist") else null
                            val sourceNamespaces =
                                database.dataSourceDao().getAll().map { it.id.sourceNamespace }
                                    .toSet()
                            for (table in GeneratedBackup.tables) {
                                if (!selection.includes(table.group)) continue
                                if (shelf != null && table.group !in setOf(
                                        BackupGroup.BOOKSHELF,
                                        BackupGroup.METADATA
                                    )
                                ) continue
                                source.query("SELECT * FROM `${table.name}`").use { cursor ->
                                    while (cursor.moveToNext()) {
                                        coroutineContext.ensureActive()
                                        val row = cursor.values()
                                        if (selection.sourceNamespace != null) {
                                            val value = row.getAsString(table.scopeColumn)
                                            val ownerNamespace =
                                                if (table.scopeType.isEmpty()) value else Identifier.parse(
                                                    value
                                                ).let {
                                                    if (it is Identifier.DataSource) it.sourceNamespace else it.namespace
                                                }
                                            if (ownerNamespace != selection.sourceNamespace && value != Identifier.ALL_BOOKS.toString()) continue
                                        }
                                        if (table.group == BackupGroup.USER_DATA) {
                                            val id = Identifier.parse(row.getAsString("id"))
                                            if (id.id == "settings.data.storage_usage_snapshot" || id.id.startsWith(
                                                    "internal.migrations."
                                                )
                                            ) continue
                                            val global = id.namespace !in sourceNamespaces
                                            if (global && !selection.settings || !global && !selection.readingRecord) continue
                                        }
                                        if (shelf != null) {
                                            val owner =
                                                Identifier.parse(row.getAsString(table.scopeColumn))
                                            val selected = when (table.scopeType) {
                                                "datasource" -> {
                                                    require(owner is Identifier.DataSource); owner.sourceNamespace == shelf.id.namespace
                                                }

                                                "bookshelf" -> owner == shelf.id
                                                "book" -> owner in shelf.allBookIds
                                                else -> error("Missing bookshelf export ownership for ${table.name}")
                                            }
                                            if (!selected) continue
                                            if (row.containsKey("book_shelf_ids")) {
                                                val ids =
                                                    Json.decodeFromString<List<Identifier.Bookshelf>>(
                                                        row.getAsString("book_shelf_ids")
                                                    )
                                                row.put(
                                                    "book_shelf_ids",
                                                    Json.encodeToString(ids.filter { it == shelf.id })
                                                )
                                            }
                                        }
                                        target.insertRow(table.name, row)
                                    }
                                }
                            }
                            target.setTransactionSuccessful()
                        } finally {
                            target.endTransaction()
                        }
                    }
                }
                ZipOutputStream(output).use { zip ->
                    zip.putNextEntry(ZipEntry("manifest.json"))
                    zip.write(
                        Json.encodeToString(
                            BackupManifest(
                                containerVersion = 1,
                                selection = selection
                            )
                        ).toByteArray(Charsets.UTF_8)
                    )
                    zip.closeEntry()
                    zip.putNextEntry(ZipEntry("database.sqlite"))
                    file.inputStream().use { it.copyTo(zip) }
                    zip.closeEntry()
                }
            } finally {
                deleteDatabaseFiles(file)
            }
        }

    suspend fun import(input: InputStream, overwrite: Boolean) = withContext(Dispatchers.IO) {
        val directory = File(context.cacheDir, "import-${UUID.randomUUID()}").apply { mkdirs() }
        val file = File(directory, "database.sqlite")
        try {
            var legacy: File? = null
            var manifest: BackupManifest? = null
            ZipInputStream(input).use { zip ->
                while (true) {
                    val entry = zip.nextEntry ?: break
                    when (entry.name) {
                        "manifest.json" -> {
                            require(manifest == null) { "Duplicate manifest" }
                            manifest =
                                Json.decodeFromString(zip.readBytes().toString(Charsets.UTF_8))
                            require(manifest!!.containerVersion == 1) { "Unsupported backup container version" }
                        }

                        "database.sqlite" -> {
                            require(!file.exists()) { "Duplicate database" }
                            file.outputStream().use { zip.copyTo(it) }
                        }

                        "data" -> {
                            require(legacy == null) { "Duplicate legacy data" }
                            legacy = File(directory, "legacy.cbor").also { out ->
                                out.outputStream().use { zip.copyTo(it) }
                            }
                        }

                        else -> error("Unknown backup entry: ${entry.name}")
                    }
                    zip.closeEntry()
                }
            }
            if (legacy != null) {
                require(!file.exists() && manifest == null) { "Mixed backup formats" }
                val converted = LegacyArchive(context).convertApp(legacy, directory)
                importFiles(converted, overwrite, legacyArchive = true)
            } else {
                require(manifest != null && file.isFile) { "Incomplete backup" }
                importFiles(listOf(file), overwrite)
            }
        } finally {
            directory.deleteRecursively()
        }
    }

    /** 先迁移并校验全部待导入数据, 再在一个事务中写入应用数据库 */
    suspend fun importFiles(
        files: List<File>,
        overwrite: Boolean,
        migrationMarker: Identifier.SettingPath? = null,
        legacyArchive: Boolean = false
    ) {
        val sources = mutableListOf<LightNovelReaderDatabase>()
        try {
            files.forEach { file ->
                val source = LightNovelReaderDatabase.openFile(context, file)
                sources.add(source)
                val db = source.openHelper.writableDatabase // 通过 Room 执行完整的增量迁移链
                db.query("PRAGMA quick_check")
                    .use { require(it.moveToFirst() && it.getString(0) == "ok") { "Invalid SQLite backup" } }
                db.query("PRAGMA foreign_key_check")
                    .use { require(!it.moveToFirst()) { "Invalid backup references" } }
                // 覆盖前通过 Room 解码所有实体, 同时校验自定义转换器的数据
                for (table in GeneratedBackup.tables) {
                    db.query("SELECT rowid FROM `${table.name}`").use { cursor ->
                        while (cursor.moveToNext()) {
                            GeneratedBackup.validate(
                                table.name,
                                source.backupAccess(),
                                SimpleSQLiteQuery(
                                    "SELECT * FROM `${table.name}` WHERE rowid = ?",
                                    arrayOf(cursor.getLong(0))
                                )
                            )
                        }
                    }
                }
            }
            val importedNamespaces = sources.flatMap { source ->
                source.dataSourceDao().getAll().map { it.id.sourceNamespace }
            }.toSet()
            database.withTransaction {
                val target = database.openHelper.writableDatabase
                if (migrationMarker != null && database.userDataDao()
                        .get(migrationMarker) != null
                ) return@withTransaction
                if (overwrite) clearSourceData(target, importedNamespaces)
                for (source in sources) {
                    if (legacyArchive) LegacyArchive(context).prepareRuleIds(source, database)
                    mergeDatabase(source, database)
                }
                if (migrationMarker != null) database.userDataDao().insert(migrationMarker, "true")
            }
        } finally {
            sources.forEach { it.close() }
        }
    }

    /** 覆盖备份所含书源的全部数据, 包括未导出的类别 */
    private fun clearSourceData(target: SupportSQLiteDatabase, namespaces: Set<String>) {
        for (table in GeneratedBackup.tables) {
            if (table.group == BackupGroup.METADATA) continue
            val column = "`" + table.scopeColumn.replace("`", "``") + "`"
            val name = "`" + table.name.replace("`", "``") + "`"
            for (namespace in namespaces) {
                if (table.scopeType.isEmpty()) {
                    target.execSQL("DELETE FROM $name WHERE $column = ?", arrayOf(namespace))
                } else {
                    // 全局设置和 book:*:* 不属于具体书源
                    val prefix = "${table.scopeType}:$namespace:"
                    target.execSQL(
                        "DELETE FROM $name WHERE substr($column, 1, length(?)) = ?",
                        arrayOf(prefix, prefix)
                    )
                }
            }
        }
    }

    private suspend fun mergeDatabase(
        source: LightNovelReaderDatabase,
        destination: LightNovelReaderDatabase
    ) {
        val from = source.openHelper.writableDatabase
        val to = destination.openHelper.writableDatabase
        for (table in GeneratedBackup.tables) {
            val autoKey = table.autoGeneratedKey
            // 先预留全部待导入的主键, 避免分配的新主键与后续记录冲突
            var nextKey = if (autoKey != null) {
                val column = "`" + autoKey.replace("`", "``") + "`"
                val sql = "SELECT IFNULL(MAX($column), 0) FROM `${table.name}`"
                maxOf(
                    from.query(sql).use { it.moveToFirst(); it.getLong(0) },
                    to.query(sql).use { it.moveToFirst(); it.getLong(0) })
            } else 0L
            val primary = from.query("PRAGMA table_info(`${table.name}`)").use { cursor ->
                buildList {
                    while (cursor.moveToNext()) if (cursor.getInt(5) > 0) add(cursor.getString(1))
                }
            }
            require(primary.isNotEmpty()) { "Backup table has no primary key: ${table.name}" }
            from.query("SELECT rowid AS __backup_rowid, * FROM `${table.name}`").use { cursor ->
                while (cursor.moveToNext()) {
                    currentCoroutineContext().ensureActive()
                    val rowid = cursor.getLong(0)
                    val row = cursor.values(start = 1)
                    val predicate = primary.joinToString(" AND ") { "`$it` = ?" }
                    val args = primary.map { row.get(it) }.toTypedArray()
                    val query =
                        SimpleSQLiteQuery("SELECT * FROM `${table.name}` WHERE $predicate", args)
                    val existing =
                        to.query(query).use { if (it.moveToFirst()) it.values() else null }
                    if (existing == null) to.insertRow(table.name, row)
                    else if (autoKey != null && existing.get(table.scopeColumn) != row.get(table.scopeColumn)) {
                        // 本地主键冲突时重新分配, 保留其他书源和全局记录
                        nextKey = Math.addExact(nextKey, 1L)
                        row.put(autoKey, nextKey)
                        to.insertRow(table.name, row)
                    } else GeneratedBackup.merge(
                        table.name, source.backupAccess(), destination.backupAccess(),
                        SimpleSQLiteQuery(
                            "SELECT * FROM `${table.name}` WHERE rowid = ?",
                            arrayOf(rowid)
                        ), query
                    )
                }
            }
        }
    }
}

internal fun Cursor.values(start: Int = 0): ContentValues = ContentValues().also { values ->
    for (index in start until columnCount) when (getType(index)) {
        Cursor.FIELD_TYPE_NULL -> values.putNull(getColumnName(index))
        Cursor.FIELD_TYPE_INTEGER -> values.put(getColumnName(index), getLong(index))
        Cursor.FIELD_TYPE_FLOAT -> values.put(getColumnName(index), getDouble(index))
        Cursor.FIELD_TYPE_BLOB -> values.put(getColumnName(index), getBlob(index))
        else -> values.put(getColumnName(index), getString(index))
    }
}

internal fun deleteDatabaseFiles(file: File) {
    listOf("", "-wal", "-shm", "-journal").forEach { File(file.absolutePath + it).delete() }
}

internal inline fun <T> LightNovelReaderDatabase.use(block: (LightNovelReaderDatabase) -> T): T =
    try {
        block(this)
    } finally {
        close()
    }
